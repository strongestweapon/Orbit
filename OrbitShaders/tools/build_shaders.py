#!/usr/bin/env python3
"""Build native Metal and portable ISF sources from the same scene algorithms."""
import json
from build_texture_shader import build_texture_shader
from pathlib import Path
from scene_parameters import PARAMETERS, COMPATIBILITY_PARAMETERS

ROOT = Path(__file__).resolve().parents[1]
SCENES = [
    ('01_chroma_flow', 'Chroma Flow', '어두운 유체 링', [5, 30], 1.0, 0.48, 0.68, 0.52),
    ('02_solar_bands', 'Solar Bands', '주황·연두 방사형 밴드', [30, 50], 1.0, 0.62, 0.32, 0.62),
    ('03_aurora_ribbon', 'Aurora Ribbon', '청보라 리본과 밝은 테두리', [50, 75], 1.0, 0.40, 0.40, 0.62),
    ('04_electric_corona', 'Electric Corona', '청백색 코로나', [75, 105], 1.0, 0.60, 0.70, 0.62),
    ('05_cyan_halo', 'Cyan Halo', '청록색 헤일로', [105, 127], 1.0, 0.32, 0.40, 0.65),
    ('06_calibration', 'Calibration', 'LED 테스트 패턴', None, 1.0, 0.50, 0.50, 0.50),
    ('07_spectral_fragments', 'Spectral Fragments', '나타나고 사라지는 빛 조각', None, 0.70, 0.55, 0.45, 0.60),
    ('08_golden_drift', 'Golden Drift', '금빛 입자와 사라지는 꼬리', None, 0.65, 0.45, 0.40, 0.65),
]
PRESENCE = {
    '01_chroma_flow': (1.00,0.80,0.25,0.00),
    '02_solar_bands': (1.00,0.80,0.25,0.00),
    '03_aurora_ribbon': (1.00,0.80,0.25,0.00),
    '04_electric_corona': (1.00,0.80,0.25,0.00),
    '05_cyan_halo': (1.00,0.80,0.25,0.00),
    '06_calibration': (1.00,0.00,0.00,0.00),
    '07_spectral_fragments': (1.00,0.25,0.35,0.00),
    '08_golden_drift': (0.76,0.95,0.24,0.03),
}
STILLS = {'07_spectral_fragments':'spectral-fragments-reference',
          '08_golden_drift':'golden-drift-reference'}
PATTERNS = ['Segments 1-5 + direction', '100x50 pixel grid', 'Inner red / outer blue',
            'RGB', '16-step gray ramp', 'White', 'Black', 'Moving marker',
            'Segment seams', 'Single-pixel checker']
LAYOUT = ['outputWidth','outputHeight','viewMode','phaseTime','density','turbulence',
          'energy','hueShift','brightness','seed','angleOffset','flipU','flipV',
          'ringWidth','testPattern','markerWidth','coverage','gapSoftness','gapMotion','fragmentation','shape0','shape1','shape2','shape3']

def float_input(name, default, minimum, maximum, label=None):
    return dict(NAME=name, LABEL=label or name, TYPE='float', DEFAULT=default, MIN=minimum, MAX=maximum)

def main():
    common = (ROOT/'src/common.glsl').read_text()
    texture_file = ROOT.parent/'OrbitTextures/manifest.json'
    textures = json.loads(texture_file.read_text())['textures'] if texture_file.exists() else {}
    for folder in ['metal','isf','config','previews']:
        (ROOT/folder).mkdir(exist_ok=True)
    manifest = {'schemaVersion':3, 'referenceVideo':'KakaoTalk_Video_2026-11-10-09-37-08.mp4',
      'logicalRing':[15444,300], 'packedRegion':[3564,1500], 'outputCanvas':[3840,2160],
      'views':{'strip':0,'ring':1,'packed4k':2},
      'coordinates':{'origin':'top-left','u':'clockwise from twelve oclock','v':'inner to outer'},
      'uniformBuffer':{'sizeBytes':96,'type':'24 tightly packed float32 values','fields':LAYOUT},
      'outputColor':'display-referred SDR RGB; RGBA8Unorm, no second sRGB encoding',
      'metalCompileOptions':{'fastMathEnabled':False},
      'parameterSchema':[
        {'id':'speed','target':'clock.speed','type':'float','min':0,'max':3},
        *[{'id':f,'target':'uniform.'+f,'type':'float','min':0,'max':1}
          for f in ['brightness','coverage','gapSoftness','gapMotion','fragmentation']],
        {'id':'hueShift','target':'uniform.hueShift','type':'float','min':-0.5,'max':0.5}],
      'testPatterns':dict(enumerate(PATTERNS)), 'scenes':[]}
    for index, (sid,name,description,reference,speed,density,turbulence,energy) in enumerate(SCENES,1):
        src=(ROOT/'src'/f'{sid}.glsl').read_text()
        defaults=dict(outputWidth=1280,outputHeight=720,viewMode=1,phaseTime=0,
          density=density,turbulence=turbulence,energy=energy,hueShift=0,brightness=1,
          seed=3,angleOffset=0,flipU=0,flipV=0,ringWidth=0.128,testPattern=0,markerWidth=12)
        defaults.update(zip(['coverage','gapSoftness','gapMotion','fragmentation'],PRESENCE[sid]))
        parameters = PARAMETERS.get(sid, [])
        compatibility = COMPATIBILITY_PARAMETERS.get(sid, [])
        all_parameters = parameters + compatibility
        defaults.update({f'shape{i}':1.0 for i in range(4)})
        defaults.update({p['id']:p['defaultValue'] for p in all_parameters})
        ns='OrbitScene'+str(index)
        entry='orbit_'+sid[3:]
        sample='''
float4 samplePixel(float2 pixel, OrbitParams p) {
    float3 uv = orbitCoordinates(pixel, p);
    if (uv.z <= 0.0) return float4(0,0,0,1);
    float presence = PRESENCE_EXPRESSION;
    float3 rgb = clamp(orbitShade(uv.xy, p) * p.brightness, 0.0, 1.0) * uv.z * presence;
    return float4(rgb, 1.0);
}
'''.replace('PRESENCE_EXPRESSION','1.0' if sid=='06_calibration' else 'orbitPresence(uv.xy, p)')
        metal=f'''// Generated by tools/build_shaders.py; edit src/{sid}.glsl instead.
#include <metal_stdlib>
using namespace metal;
#define vec2 float2
#define vec3 float3
#define vec4 float4
#define ORBIT_ATAN atan2
namespace {ns} {{
{common}
{src}
{sample}
}}
kernel void {entry}_compute(device uchar4* output [[buffer(0)]],
    constant {ns}::OrbitParams &p [[buffer(1)]], uint2 gid [[thread_position_in_grid]]) {{
    if (gid.x >= uint(p.outputWidth) || gid.y >= uint(p.outputHeight)) return;
    float4 c = {ns}::samplePixel(float2(gid) + 0.5, p);
    output[gid.y * uint(p.outputWidth) + gid.x] = uchar4(c * 255.0 + 0.5);
}}
fragment float4 {entry}_fragment(float4 position [[position]],
    constant {ns}::OrbitParams &p [[buffer(0)]]) {{
    return {ns}::samplePixel(position.xy, p);
}}
#undef vec2
#undef vec3
#undef vec4
#undef ORBIT_ATAN
#undef ORBIT_TAU
'''
        (ROOT/'metal'/f'{sid}.metal').write_text(metal)
        inputs=[dict(NAME='viewMode',LABEL='View',TYPE='long',DEFAULT=1,VALUES=[0,1,2],LABELS=['Unwrapped','Ring preview','Packed 4K']),
          float_input('speed',speed,0,3),dict(NAME='externalClock',LABEL='Use continuous host clock',TYPE='bool',DEFAULT=False),
          float_input('clockSeconds',0,0,86400),float_input('density',density,0,1),
          float_input('turbulence',turbulence,0,1),float_input('energy',energy,0,1),
          float_input('hueShift',0,-0.5,0.5),float_input('brightness',1,0,1),
          float_input('seed',3,0,100),float_input('angleOffset',0,-1,1),
          dict(NAME='flipU',LABEL='Reverse direction',TYPE='bool',DEFAULT=False),
          dict(NAME='flipV',LABEL='Swap inner / outer',TYPE='bool',DEFAULT=False),
          float_input('ringWidth',0.128,0.01,0.6)]
        inputs += [float_input(f,defaults[f],0,1) for f in ['coverage','gapSoftness','gapMotion','fragmentation']]
        if sid=='06_calibration':
            inputs += [dict(NAME='testPattern',LABEL='Test pattern',TYPE='long',DEFAULT=0,
                            VALUES=list(range(10)),LABELS=PATTERNS),float_input('markerWidth',12,1,300)]
        # Expose semantic IDs in ISF too; legacy slots remain internal.
        replaced = {p['uniform'] for p in all_parameters}
        inputs = [item for item in inputs if item['NAME'] not in replaced]
        inputs += [float_input(p['id'],p['defaultValue'],p['minimum'],p['maximum'],p['title']) for p in parameters]
        meta={'ISFVSN':'2.0','VSN':'1.4.0','DESCRIPTION':description+' / '+name,
              'CREDIT':'SUPERLESS / Orbit project; procedural study based on supplied reference video',
              'CATEGORIES':['Generator','Orbit'],'INPUTS':inputs}
        assignments='\n'.join('    p.'+f+' = '+expr+';' for f,expr in {
          'outputWidth':'RENDERSIZE.x','outputHeight':'RENDERSIZE.y','viewMode':'float(viewMode)',
          'phaseTime':'externalClock ? clockSeconds : TIME * speed','density':'density',
          'turbulence':'turbulence','energy':'energy','hueShift':'hueShift','brightness':'brightness',
          'seed':'seed','angleOffset':'angleOffset','flipU':'flipU ? 1.0 : 0.0',
          'flipV':'flipV ? 1.0 : 0.0','ringWidth':'ringWidth',
          'testPattern':'float(testPattern)' if sid=='06_calibration' else '0.0',
          'markerWidth':'markerWidth' if sid=='06_calibration' else '12.0',
          **{f:f for f in ['coverage','gapSoftness','gapMotion','fragmentation']}}.items())
        for p in all_parameters:
            value = p['id'] if p in parameters else str(float(p['defaultValue']))
            assignments = assignments.replace('p.'+p['uniform']+' = '+p['uniform']+';', 'p.'+p['uniform']+' = '+value+';')
        for slot in ['shape0','shape1','shape2','shape3']:
            value = next((p['id'] if p in parameters else str(float(p['defaultValue'])) for p in all_parameters if p['uniform']==slot),'1.0')
            assignments += '\n    p.'+slot+' = '+value+';'
        isf='/*'+json.dumps(meta,ensure_ascii=False,indent=2)+'*/\n#define ORBIT_ATAN atan\n'+common+'\n'+src+'''
void main() {
    OrbitParams p;
'''+assignments+'''
    vec2 pixel = vec2(isf_FragNormCoord.x, 1.0-isf_FragNormCoord.y) * RENDERSIZE;
    vec3 uv = orbitCoordinates(pixel, p);
    float presence = PRESENCE_EXPRESSION;
    vec3 color = uv.z > 0.0 ? clamp(orbitShade(uv.xy, p) * brightness, 0.0, 1.0) * uv.z * presence : vec3(0.0);
    gl_FragColor = vec4(color, 1.0);
}
'''.replace('PRESENCE_EXPRESSION','1.0' if sid=='06_calibration' else 'orbitPresence(uv.xy, p)')
        (ROOT/'isf'/f'{sid}.fs').write_text(isf)
        manifest['scenes'].append(dict(id=sid,name=name,description=description,referenceSeconds=reference,
            metal=f'metal/{sid}.metal',isf=f'isf/{sid}.fs',computeFunction=entry+'_compute',
            fragmentFunction=entry+'_fragment',parameters=parameters,compatibilityParameters=compatibility,
            defaults=defaults,defaultClockSpeed=speed,
            sensorMappingEnabled=sid!='06_calibration',testScene=sid=='06_calibration',referenceImage=STILLS.get(sid),texture=textures.get(sid)))
    (ROOT/'metal/OrbitFullscreen.metal').write_text('''#include <metal_stdlib>
using namespace metal;
vertex float4 orbit_fullscreen_vertex(uint id [[vertex_id]]) {
    const float2 p[3] = { float2(-1,-1), float2(3,-1), float2(-1,3) };
    return float4(p[id],0,1);
}
''')
    (ROOT/'config/scenes.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    mappings={'schemaVersion':1,'status':'example bindings; native app supports per-parameter OSC input and MIDI/OSC output',
      'osc':{'bindAddress':'0.0.0.0','udpPort':9000,'expectedIntervalSeconds':30,'staleAfterSeconds':90},
      'sensors':[{'id':'racing_speed','address':'/park/racing/speed','argument':0,'type':'float','range':[0,100]},
                 {'id':'visitors','address':'/park/visitors','argument':0,'type':'int','range':[0,500]}],
      'scenes':{}}
    for scene in manifest['scenes']:
        if scene['testScene']: mappings['scenes'][scene['id']]=[]; continue
        first_control=scene['parameters'][0]
        second_control=scene['parameters'][1]
        mappings['scenes'][scene['id']]=[
          {'sensor':'racing_speed','target':'clock.speed','outputRange':[0.25,1.5],
           'clamp':True,'smoothingSeconds':8,'staleTarget':scene['defaultClockSpeed']},
          {'sensor':'visitors','target':'parameter.'+first_control['id'],
           'outputRange':[first_control['minimum'],first_control['maximum']],
           'clamp':True,'smoothingSeconds':12,'staleTarget':first_control['defaultValue']},
          {'sensor':'racing_speed','target':'parameter.'+second_control['id'],
           'outputRange':[second_control['minimum'],second_control['maximum']],
           'clamp':True,'smoothingSeconds':8,'staleTarget':second_control['defaultValue']}]
    (ROOT/'config/osc-mappings.example.json').write_text(json.dumps(mappings,ensure_ascii=False,indent=2)+'\n')
    build_texture_shader()
    print(f'Built {len(SCENES)} Metal shaders and ISF generators; 96-byte uniform layout.')

if __name__=='__main__': main()
